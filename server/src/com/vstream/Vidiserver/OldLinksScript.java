package com.vstream.Vidiserver;

/** The VPS script that puts the old Centova address on this server (served at /radio/oldlinks.sh). Made from oldlinks.sh. */
final class OldLinksScript {

    private OldLinksScript() {
    }

    static final String TEXT = ""
            + "#!/bin/bash\n"
            + "# Memoryq: the old listening links keep working after the stations moved from Centova / Azuracast.\n"
            + "#   sudo bash oldlinks.sh          puts the old Centova address (184.75.212.211) on this server, so\n"
            + "#                                  http://184.75.212.211:PORT/stream plays the moved station\n"
            + "#   sudo bash oldlinks.sh status   shows what is set up\n"
            + "#   sudo bash oldlinks.sh down     takes the old address off this server again\n"
            + "# Safe to run again. If this server stops reaching the internet after the change, it is undone by itself.\n"
            + "# Other values:  OLD_IP=... OLD_PREFIX=24 OLD_GW=... sudo -E bash oldlinks.sh\n"
            + "set -u\n"
            + "OLD_IP=\"${OLD_IP:-184.75.212.211}\"\n"
            + "OLD_PREFIX=\"${OLD_PREFIX:-24}\"\n"
            + "OLD_GW=\"${OLD_GW:-184.75.212.209}\"\n"
            + "TABLE=211\n"
            + "MODE=\"${1:-up}\"\n"
            + "HELPER=/usr/local/sbin/memoryq-oldip\n"
            + "UNIT=/etc/systemd/system/memoryq-oldip.service\n"
            + "\n"
            + "say() { echo \"$*\"; }\n"
            + "fail() { echo; echo \"STOPPED: $*\"; exit 1; }\n"
            + "[ \"$(id -u)\" = \"0\" ] || fail \"run it with sudo:  sudo bash $0\"\n"
            + "\n"
            + "DEV=$(ip -4 route show default | awk '{for (i = 1; i < NF; i++) if ($i == \"dev\") {print $(i + 1); exit}}')\n"
            + "[ -n \"$DEV\" ] || fail \"the network card was not found (no default route).\"\n"
            + "MY_IP=$(ip -4 -o addr show dev \"$DEV\" | awk '{print $4}' | cut -d/ -f1 | grep -v \"^$OLD_IP$\" | head -n 1)\n"
            + "\n"
            + "# ---- the helper that adds / removes the address (also used at every start of the server) ----\n"
            + "write_helper() {\n"
            + "  cat > \"$HELPER\" <<EOF\n"
            + "#!/bin/bash\n"
            + "# Memoryq: the old Centova address on this server, with its own way out (replies leave through $OLD_GW).\n"
            + "case \"\\$1\" in\n"
            + "  up)\n"
            + "    ip -4 addr show dev $DEV | grep -q \" $OLD_IP/\" || ip addr add $OLD_IP/$OLD_PREFIX dev $DEV\n"
            + "    ip route replace default via $OLD_GW dev $DEV table $TABLE\n"
            + "    ip route replace $(echo \"$OLD_IP\" | cut -d. -f1-3).0/$OLD_PREFIX dev $DEV src $OLD_IP table $TABLE\n"
            + "    ip rule show | grep -q \"from $OLD_IP lookup $TABLE\" || ip rule add from $OLD_IP lookup $TABLE priority $TABLE\n"
            + "    ;;\n"
            + "  down)\n"
            + "    while ip rule show | grep -q \"from $OLD_IP lookup $TABLE\"; do ip rule del from $OLD_IP lookup $TABLE; done\n"
            + "    ip route flush table $TABLE 2>/dev/null\n"
            + "    ip addr del $OLD_IP/$OLD_PREFIX dev $DEV 2>/dev/null\n"
            + "    ;;\n"
            + "esac\n"
            + "exit 0\n"
            + "EOF\n"
            + "  chmod 755 \"$HELPER\"\n"
            + "  cat > \"$UNIT\" <<EOF\n"
            + "[Unit]\n"
            + "Description=Memoryq - old Centova address $OLD_IP (old radio links)\n"
            + "After=network-online.target\n"
            + "Wants=network-online.target\n"
            + "\n"
            + "[Service]\n"
            + "Type=oneshot\n"
            + "RemainAfterExit=yes\n"
            + "ExecStart=$HELPER up\n"
            + "ExecStop=$HELPER down\n"
            + "\n"
            + "[Install]\n"
            + "WantedBy=multi-user.target\n"
            + "EOF\n"
            + "  systemctl daemon-reload\n"
            + "}\n"
            + "\n"
            + "show_status() {\n"
            + "  echo \"Network card: $DEV ($MY_IP)\"\n"
            + "  if ip -4 addr show dev \"$DEV\" | grep -q \" $OLD_IP/\"; then echo \"Old address $OLD_IP: ON this server\"; else echo \"Old address $OLD_IP: not on this server\"; fi\n"
            + "  ip rule show | grep -q \"from $OLD_IP lookup $TABLE\" && echo \"Its own way out (through $OLD_GW): yes\" || echo \"Its own way out: no\"\n"
            + "  systemctl is-enabled memoryq-oldip >/dev/null 2>&1 && echo \"Comes back after a restart: yes\" || echo \"Comes back after a restart: no\"\n"
            + "  local open\n"
            + "  open=$(ss -ltn 2>/dev/null | awk '{print $4}' | grep \"^$OLD_IP:\" | sed \"s/^$OLD_IP://\" | sort -n | tr '\\n' ' ')\n"
            + "  echo \"Old ports open: ${open:-none yet (Memoryq opens them within a minute of the address being here)}\"\n"
            + "}\n"
            + "\n"
            + "case \"$MODE\" in\n"
            + "  status) show_status; exit 0 ;;\n"
            + "  down)\n"
            + "    systemctl disable --now memoryq-oldip >/dev/null 2>&1\n"
            + "    [ -x \"$HELPER\" ] && \"$HELPER\" down\n"
            + "    say \"The old address $OLD_IP is off this server.\"\n"
            + "    exit 0 ;;\n"
            + "  up) ;;\n"
            + "  *) fail \"unknown mode $MODE (up, status or down)\" ;;\n"
            + "esac\n"
            + "\n"
            + "# ---- 1. the old address ----\n"
            + "if ip -4 addr show dev \"$DEV\" | grep -q \" $OLD_IP/\"; then\n"
            + "  say \"The old address $OLD_IP is already on this server.\"\n"
            + "else\n"
            + "  say \"Checking that nothing else uses $OLD_IP (the Centova server must be shut down)...\"\n"
            + "  busy=\"another machine still answers on $OLD_IP - shut down the Centova server (VM 211) in ESXi first, then run this again.\"\n"
            + "  if ping -c 2 -W 2 \"$OLD_IP\" >/dev/null 2>&1; then fail \"$busy\"; fi\n"
            + "  if command -v arping >/dev/null 2>&1 && arping -V 2>&1 | grep -qi iputils; then\n"
            + "    arping -D -q -c 3 -w 4 -I \"$DEV\" \"$OLD_IP\" || fail \"$busy\"\n"
            + "  fi\n"
            + "fi\n"
            + "write_helper\n"
            + "\"$HELPER\" up\n"
            + "systemctl enable memoryq-oldip >/dev/null 2>&1\n"
            + "systemctl start memoryq-oldip >/dev/null 2>&1\n"
            + "sleep 2\n"
            + "\n"
            + "# ---- 2. still online? (undo by itself if not) ----\n"
            + "ok_main=$(curl -s -o /dev/null -m 15 -w '%{http_code}' https://www.google.com/ || true)\n"
            + "ok_old=$(curl -s -o /dev/null -m 15 --interface \"$OLD_IP\" -w '%{http_code}' https://www.google.com/ || true)\n"
            + "if [ \"$ok_main\" = \"000\" ]; then\n"
            + "  systemctl disable --now memoryq-oldip >/dev/null 2>&1; \"$HELPER\" down\n"
            + "  fail \"this server could not reach the internet after the change - it was undone. Nothing else was changed.\"\n"
            + "fi\n"
            + "if [ \"$ok_old\" = \"000\" ]; then\n"
            + "  systemctl disable --now memoryq-oldip >/dev/null 2>&1; \"$HELPER\" down\n"
            + "  fail \"the old address could not reach the internet through $OLD_GW - it was undone. Check OLD_GW / OLD_PREFIX (see ip route on the old server).\"\n"
            + "fi\n"
            + "say \"The old address $OLD_IP is on this server and reaches the internet through $OLD_GW.\"\n"
            + "\n"
            + "# ---- 3. the firewall: the old Centova ports ----\n"
            + "if command -v ufw >/dev/null 2>&1; then\n"
            + "  ufw allow 8000:8009/tcp >/dev/null 2>&1 && say \"Firewall: old Centova ports 8000-8009 open.\"\n"
            + "fi\n"
            + "\n"
            + "echo\n"
            + "show_status\n"
            + "echo\n"
            + "echo \"Test from your PC in about a minute:  curl -I http://$OLD_IP:8005/stream\"\n"
            + "echo \"Memoryq Admin - Radio - Import - Old listening links shows each old link and the station it plays.\"\n";
}